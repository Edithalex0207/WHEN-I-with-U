/**
 * 取某张卡的小故事，{name} 换成小伙伴的名字。没有对应故事返回空字符串
 * （调用方会退回显示卡池里那句短文案）。
 */
export const getCardStory = (cardId, companionName) => {
  const raw = CARD_STORIES[cardId];
  if (!raw) return '';
  return raw.replace(/\{name\}/g, companionName || '小伙伴');
};
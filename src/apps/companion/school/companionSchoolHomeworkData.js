/*
 * 题目格式：
 *   { id, stem, mateAnswer, isCorrect, rightAnswer }
 *   stem         题干
 *   mateAnswer   同学写在作业本上的答案
 *   isCorrect    同学的答案是不是对的（对错本地已知）
 *   rightAnswer  标准答案；isCorrect 为 true 时跟 mateAnswer 一样
 * 玩家批改时看不到标准答案，揭晓时才显示批反的题的标准答案。
 *
 * 每个学段每个科目至少 6 题，每科里对的和错的都有，
 * 抽题时（companionSchoolHomeworkService.js）会保证一份作业里有对有错。
 * id 一旦发出去就不要改。
 */
const q = (id, stem, mateAnswer, rightAnswer) => ({
  id,
  stem,
  mateAnswer,
  isCorrect: mateAnswer === rightAnswer,
  rightAnswer,
});

